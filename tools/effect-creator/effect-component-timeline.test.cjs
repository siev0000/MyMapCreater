const C=require("./effect-components.js");
const assert=(v,m)=>{if(!v)throw Error(m)};
const near=(a,b)=>Math.abs(a-b)<1e-6;
const reject=(fn,m)=>{let bad=false;try{fn()}catch{bad=true}assert(bad,m)};
const R=C.timelineRange;
let r=R(.2,1.2,3,"move",.76,.1);assert(near(r.start,1)&&near(r.end,2),"snap move");
r=R(.2,1.2,3,"move",-20,.1);assert(r.start===0&&near(r.end,1),"left bound");
r=R(.2,1.2,3,"move",20,.1);assert(near(r.start,2)&&r.end===3,"right bound");
r=R(.2,1.2,3,"start",20,.1);assert(r.end===1.2&&near(r.start,1.19),"start cannot cross end");
r=R(.2,1.2,3,"end",-20,.1);assert(r.start===.2&&near(r.end,.21),"end cannot cross start");
r=R(.123,.789,3,"move",0,.1);assert(r.start===.123&&r.end===.789,"no movement no snap");
r=R(.123,.789,3,"move",.2,0);assert(near(r.end-r.start,.666),"duration preserved");
r=R(.2,1.2,3,"start",-1,.1);assert(r.start===0&&r.end===1.2,"start bound");
r=R(.2,1.2,3,"end",10,.1);assert(r.start===.2&&r.end===3,"end bound");
r=R(.2,1.2,3,"move",.3,1/12);assert(near(r.start,.5)&&near(r.end,1.5),"frame snap");
r=R(.2,.205,3,"start",.1,0);assert(r.start===.2||near(r.start,.2),"short interval preserved");
reject(()=>R(.2,.1,3,"move",0),"invalid interval");reject(()=>R(0,1,3,"bad",1),"invalid mode");reject(()=>R(0,1,3,"move",Infinity),"invalid delta");
const c=C.sample("inferno"),before=JSON.stringify(c),uid=c.parts[0].uid;
const result=C.changeTiming(c,uid,.1,2.2);assert(JSON.stringify(c)===before,"input unchanged");assert(result.parts[0].start===.1&&result.parts[0].end===2.2,"changed selected timing");assert(JSON.stringify(result.parts.slice(1))===JSON.stringify(c.parts.slice(1)),"other parts unchanged");assert(C.compile(result).source!==C.compile(c).source,"shader updated");
reject(()=>C.changeTiming(c,uid,2.5,1),"crossed");reject(()=>C.changeTiming(c,uid,0,4),"outside duration");reject(()=>C.changeTiming(c,"missing",0,1),"missing uid");
console.log("timeline model tests passed");